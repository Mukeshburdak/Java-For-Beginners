class Main{
    public static void main(String[] args){
        int a = 30;
        int b = 20;
        //Addition
        System.out.println(a+b);

        //Subtract
        System.out.println(a-b);

        //Multiplication
        System.out.println(a*b);

        //Division
        System.out.println(a/b);

        //Float division
        System.out.println(a/(float)b);

        //Modulo operator - Remainder
        System.out.println(a%b);
    }
}